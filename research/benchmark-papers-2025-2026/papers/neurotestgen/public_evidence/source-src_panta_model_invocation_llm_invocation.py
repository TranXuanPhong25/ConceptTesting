import time
import random
import os
import logging
from openai import OpenAI, NotFoundError, AuthenticationError


class LLMInvocation:
    def __init__(self, model: str):
        self.model = model
        self.logger = logging.getLogger(__name__)

        # Initialize OpenAI client with OpenRouter
        api_key = os.getenv("OPENROUTER_API_KEY")
        if not api_key:
            raise ValueError("OPENROUTER_API_KEY environment variable not set")

        self.client = OpenAI(
            base_url="https://openrouter.ai/api/v1",
            api_key=api_key,
        )

    def call_model(self, prompt: dict, max_tokens=4096, temperature=0.2):
        """
        Returns:
            tuple: A tuple containing the response generated by the LLM,
            the number of tokens used from the prompt, and the total number of tokens in the response.
        """
        if "system" not in prompt or "user" not in prompt:
            raise KeyError("The prompt dictionary must contain 'system' and 'user' keys.")

        if prompt["system"] == "":
            messages = [{"role": "user", "content": prompt["user"]}]
        else:
            messages = [
                {"role": "system", "content": prompt["system"]},
                {"role": "user", "content": prompt["user"]},
            ]

        completion_params = {
            "model": self.model,
            "messages": messages,
            "max_tokens": max_tokens,
            "stream": True,
            "temperature": temperature,
            "stream_options": {"include_usage": True},  # Include usage info in final chunk
        }
        # print("====== Prompt: ======\n", messages)

        max_retries = 5
        base_delay = 2  # base delay in seconds

        for attempt in range(max_retries):
            try:
                response = self.client.chat.completions.create(**completion_params)

                # Collect streamed chunks
                full_content = ""
                prompt_tokens = 0
                completion_tokens = 0

                for chunk in response:
                    # Content chunks
                    if chunk.choices and len(chunk.choices) > 0 and chunk.choices[0].delta.content:
                        content = chunk.choices[0].delta.content
                        # print(content, end="", flush=True)
                        full_content += content
                        time.sleep(0.01)

                    # Usage info in final chunk
                    if hasattr(chunk, 'usage') and chunk.usage:
                        prompt_tokens = chunk.usage.prompt_tokens
                        completion_tokens = chunk.usage.completion_tokens

                print("\n")

                return (full_content, prompt_tokens, completion_tokens)

            except NotFoundError as e:
                # Model not found or not supported
                error_msg = f"Model '{self.model}' not found or not supported by OpenRouter. Please check the model name."
                self.logger.error(error_msg)
                self.logger.error(f"Error details: {e}")
                raise RuntimeError(error_msg) from e

            except AuthenticationError as e:
                # API key issues
                error_msg = "Authentication failed. Please check your OPENROUTER_API_KEY."
                self.logger.error(error_msg)
                self.logger.error(f"Error details: {e}")
                raise RuntimeError(error_msg) from e

            except Exception as e:
                # Other errors - retry with exponential backoff
                delay = base_delay * (2 ** attempt) + random.uniform(0, 1)
                error_msg = f"API call failed: {e}. Retrying in {delay:.2f} seconds... (Attempt {attempt + 1}/{max_retries})"
                self.logger.warning(error_msg)
                print(error_msg)
                time.sleep(delay)

        raise RuntimeError("Max retries exceeded. Could not complete API call.")
