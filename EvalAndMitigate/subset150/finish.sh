#!/usr/bin/env bash
# subset150 last stage (host), after the tests+evals chain: redo glitched new-method blocks once per arm (NO_ADC=1 via
# eval_parts.py), then the analysis and a draft RESULTS.md.
# usage (from EvalAndMitigate/): bash subset150/finish.sh > subset150/out/finish.console 2>&1
set -euo pipefail
cd "$(dirname "$0")/.."
D=subset150
grep -q "chain exit 0" $D/out/chain.done || { echo "tests/evals chain did not end with exit 0: $(cat $D/out/chain.done)"; exit 1; }
for a in concept placebo rerun adv onlydoc; do
  g=$(python3 $D/analyze.py glitched s150_$a)
  if [ -n "$g" ] && ! grep -q '"idx"' $D/out/s150_${a}_parts.json; then
    echo "redo s150_$a: $g"; python3 $D/eval_parts.py s150_$a --redo $g
  fi
done
python3 $D/analyze.py > $D/out/analysis.txt
{ echo "# subset150: results (DRAFT, generated by finish.sh from out/analysis.txt; numbers not yet interpreted)"
  echo; echo "Sampling, arms and commands: README.md. Every number below: \`python3 subset150/analyze.py\`."
  echo; cat $D/out/analysis.txt; } > $D/RESULTS.md
echo "analysis and draft RESULTS.md written"
