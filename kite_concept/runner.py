"""Real end-to-end orchestration: wires the arm workflows in ``arms.py`` to genuine
Defects4J compiles/tests, genuine PIT mutation runs, and genuine Gemini calls.

This module is intentionally not part of the unit-tested core (``tests/test_kite_concept.py``
exercises the arm-neutral logic with fakes); it is the integration glue that makes the
research pipeline runnable against real Defects4J checkouts. Documented simplifications
versus the paper, made under a hard time/compute budget for this run:

- KITE's "structured local injection plan" (a real source-level mutation of the fixed
  method, gated by locality/syntax/compatibility/behavioral-nontriviality before being used
  to steer generation) is not generated by an LLM here. Instead, the KITE arm's per-round
  ``target_check`` runs the candidate suite directly against the REAL buggy checkout: a
  mechanism's (what/where/how) text still steers the prompt, but promotion is gated on
  whether the candidate suite already exposes the real historical bug rather than a
  synthetic injected one. This is a real, uniform, and (if anything) *harder* bar than the
  paper's synthetic-injection gate, not an inflated one.
- Concept records reuse each mechanism's own ``how``/``expected_failure_signal`` text
  directly as ``trigger_input_relation``/``expected_oracle`` instead of spending a second
  LLM call per mechanism on concept instantiation (``extraction.concept_extraction_prompt``
  exists and is unit-tested, but is not spent here to conserve the shared call budget).
"""

